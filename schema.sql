-- ==========================================
-- 5. Supabase Storage Setup (for candidate photos/logos)
-- ==========================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('candidate-images', 'candidate-images', true)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "Allow public select access to candidate-images" ON storage.objects;
CREATE POLICY "Allow public select access to candidate-images"
ON storage.objects FOR SELECT USING (bucket_id = 'candidate-images');

DROP POLICY IF EXISTS "Allow public insert access to candidate-images" ON storage.objects;
CREATE POLICY "Allow public insert access to candidate-images"
ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'candidate-images');

DROP POLICY IF EXISTS "Allow public delete access to candidate-images" ON storage.objects;
CREATE POLICY "Allow public delete access to candidate-images"
ON storage.objects FOR DELETE USING (bucket_id = 'candidate-images');
